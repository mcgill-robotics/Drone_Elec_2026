/**
* @brief Function implementing the sensorTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_sensorTask_Init */
void sensorTask_Init(void const * argument)
{
  /* USER CODE BEGIN sensorTask_Init */
  uint8_t sensorData[4];
  /* Infinite loop */
  for(;;)
  {
    HAL_I2C_Master_Receive_DMA(&hi2c2, SENSOR_ADDRESS, &sensorData, 4);
    // Byte 0: [S[1:0] P[13:8]]
    // Byte 1: [P[7:0]]
    // Byte 2: [T[10:3]]
    // Byte 3: [T[2:0] X X X X X]
    rawAirData.status = sensorData[0] >> 6;
    rawAirData.pressure = ((sensorData[0] & 0x3F) << 8) | sensorData[1];
    rawAirData.temp = (sensorData[2] << 3) | (sensorData[3] >> 5);
    osDelay(10);
  }
  /* USER CODE END sensorTask_Init */
}

